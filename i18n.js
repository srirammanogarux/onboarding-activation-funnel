let L10N = 'en';
function T(key, ...args){
  const v = (STR[L10N] && STR[L10N][key] !== undefined) ? STR[L10N][key] : STR.en[key];
  return typeof v === 'function' ? v(...args) : v;
}

/* Content-label lookup. Branch data (goals, situations, scenarios,
   option rows, screen furniture) keeps its ENGLISH string as the key;
   each locale translates it under STR.<locale>.content. Unknown strings
   fall back to themselves, so partial dictionaries degrade gracefully.
   The English being *practised* (readings, drills, model answers) is
   deliberately never passed through here — this is an English app. */
/* The language they told us they speak, set the moment they pick it.
   Distinct from L10N: the app can stay in English while the reading
   card still explains a line in their own language. */
let NATIVE = 'fr';
function NL(label, loc){
  if (label == null) return label;
  const m = STR[loc || NATIVE] && STR[loc || NATIVE].content;
  return (m && m[label]) || label;
}

function CL(label){
  if (label == null) return label;
  const m = STR[L10N] && STR[L10N].content;
  return (m && m[label]) || label;
}
